#!/usr/bin/env python3
"""Resolve Debian binaries through authenticated, time-bounded archive metadata."""
import argparse
import datetime as dt
import email.utils
import hashlib
import json
import lzma
import re
import subprocess
import tempfile
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ARCHIVE = 'https://deb.debian.org/debian'
SUITE = 'sid'


def fields(text):
    result = {}
    key = None
    for line in text.splitlines():
        if line.startswith(' ') and key:
            result[key] += '\n' + line[1:]
        elif ':' in line:
            key, value = line.split(':', 1)
            result[key] = value.lstrip()
    return result


def fetch(url):
    with urllib.request.urlopen(url, timeout=120) as response:
        return response.read()


def checked_path(path):
    if not re.fullmatch(r'[A-Za-z0-9_+./~-]+', path) or any(p in ('', '.', '..') for p in path.split('/')):
        raise ValueError(f'Unsafe archive path: {path!r}')
    return path


def verify_release(text, now=None):
    data = fields(text)
    now = now or dt.datetime.now(dt.timezone.utc)
    issued = email.utils.parsedate_to_datetime(data['Date'])
    if issued > now + dt.timedelta(hours=1) or now - issued > dt.timedelta(days=7):
        raise ValueError('Release metadata is stale or from the future')
    if 'Valid-Until' in data and email.utils.parsedate_to_datetime(data['Valid-Until']) < now:
        raise ValueError('Release metadata has expired')
    if data.get('Codename') != SUITE or 'amd64' not in data.get('Architectures', '').split():
        raise ValueError('Unexpected Debian suite or architecture')
    return data


def resolve_kernel(records):
    meta = records['linux-image-amd64']
    match = re.search(r'\b(linux-image-[0-9][A-Za-z0-9.+~-]*-amd64)\s*\(= ([^)]+)\)', meta['Depends'])
    if not match:
        raise ValueError('Cannot resolve signed amd64 kernel')
    image_name, version = match.groups()
    image = records[image_name]
    if image['Version'] != version or 'linux-signed-amd64' not in image.get('Source', ''):
        raise ValueError('Kernel image is not the expected Debian signed build')
    names = [image_name]
    # New Debian releases split image/base/modules; older ones carry them in linux-image.
    for name, dep_version in re.findall(r'\b(linux-(?:binary|base|modules)-[A-Za-z0-9.+~-]+)\s*\(= ([^)]+)\)', image.get('Depends', '')):
        if records[name]['Version'] != dep_version:
            raise ValueError(f'Inconsistent dependency: {name}')
        names.append(name)
    return version, image_name.removeprefix('linux-image-'), names


def pkgver(version):
    if not re.fullmatch(r'[0-9][A-Za-z0-9.+~-]*', version):
        raise ValueError(f'Unsupported Debian version: {version}')
    return version.replace('-', '.deb').replace('+', '.').replace('~', '.')


def recipe(name, version, entries, kernel_abi=None):
    lines = [
        '# Generated by scripts/update.py; edit the generator instead.',
        f'pkgname={name}', f'pkgver={pkgver(version)}', 'pkgrel=1',
        'pkgdesc="Official Debian signed binaries repackaged for Arch Linux"',
        "arch=('x86_64')", 'url="https://www.debian.org/"',
        "license=('GPL-2.0-only')" if kernel_abi else ("license=('BSD-3-Clause')" if name.startswith('shim') else "license=('LGPL-2.1-or-later')"),
        "options=('!strip' '!debug')",
        "depends=('coreutils' 'kmod' 'mkinitcpio')" if kernel_abi else "depends=()",
        "makedepends=('libarchive')", 'source=('
    ]
    for entry in entries:
        lines.append(f"    '{ARCHIVE}/{entry['filename']}'")
    lines += [')', 'sha256sums=('] + [f"    '{e['sha256']}'" for e in entries] + [')', '', 'package() {']
    lines += ['    local archive member', '    for archive in "${source[@]}"; do', '        archive="${archive##*/}"', '        member=$(bsdtar -tf "$srcdir/$archive" | sed -n \'/^data\\.tar/{p;q;}\')', '        bsdtar -xOf "$srcdir/$archive" "$member" | bsdtar -xf - -C "$pkgdir"', '    done']
    if kernel_abi:
        lines += [f'    local modules="$pkgdir/usr/lib/modules/{kernel_abi}"',
                  '    if [[ -d "$pkgdir/lib/modules" ]]; then',
                  '        install -d "$pkgdir/usr/lib"',
                  '        cp -a "$pkgdir/lib/modules" "$pkgdir/usr/lib/"',
                  '        rm -rf "$pkgdir/lib"', '    fi',
                  '    if [[ ! -f "$modules/vmlinuz" ]]; then',
                  f'        install -Dm644 "$pkgdir/boot/vmlinuz-{kernel_abi}" "$modules/vmlinuz"', '    fi',
                  '    printf \'%s\\n\' "$pkgname" > "$modules/pkgbase"',
                  '    rm -rf "$pkgdir/boot"',
                  '    install -Dm644 "$startdir/linux-debian-bin.preset" "$pkgdir/etc/mkinitcpio.d/linux-debian-bin.preset"']
    elif name == 'systemd-boot-debian-bin':
        lines += [
            '    install -d "$pkgdir/usr/lib/arch-debian-kernel/systemd-boot"',
            '    mv "$pkgdir/usr/lib/systemd/boot/efi/systemd-bootx64.efi.signed" "$pkgdir/usr/lib/arch-debian-kernel/systemd-boot/"',
            '    rmdir "$pkgdir/usr/lib/systemd/boot/efi" "$pkgdir/usr/lib/systemd/boot" "$pkgdir/usr/lib/systemd"',
        ]
    # Debian docs/copyright remain in the payload; retain original signed EFI and .ko bytes.
    lines += ['}', '']
    return '\n'.join(lines)


def preserve_release(generated, previous):
    version = re.search(r'^pkgver=(.+)$', generated, re.M)[1]
    if f'pkgver={version}\n' not in previous:
        return generated
    release = int(re.search(r'^pkgrel=([0-9]+)$', previous, re.M)[1])
    normalize = lambda text: re.sub(r'^pkgrel=[0-9]+$', 'pkgrel=1', text, flags=re.M)
    if normalize(generated) != normalize(previous):
        release += 1
    return generated.replace('pkgrel=1\n', f'pkgrel={release}\n')


def update(keyring):
    with tempfile.TemporaryDirectory() as temporary:
        tmp = Path(temporary)
        signed = tmp / 'InRelease'
        release = tmp / 'Release'
        signed.write_bytes(fetch(f'{ARCHIVE}/dists/{SUITE}/InRelease'))
        subprocess.run(['gpgv', '--keyring', str(keyring), '--output', str(release), str(signed)], check=True)
        info = verify_release(release.read_text())
        index_path = 'main/binary-amd64/Packages.xz'
        checksum = next(line.split() for line in info['SHA256'].splitlines() if line.split()[-1:] == [index_path])
        index = fetch(f'{ARCHIVE}/dists/{SUITE}/{index_path}')
        if len(index) != int(checksum[1]) or hashlib.sha256(index).hexdigest() != checksum[0]:
            raise ValueError('Package index checksum or size mismatch')
        records = {}
        for block in lzma.decompress(index).decode().split('\n\n'):
            data = fields(block)
            if data.get('Package', '').startswith(('linux-', 'shim-', 'systemd-boot-')):
                records[data['Package']] = data
        version, abi, kernel_names = resolve_kernel(records)
        helper_version = records['shim-helpers-amd64-signed']['Version']
        if not helper_version:
            raise ValueError('Missing signed Shim helpers')
        groups = {
            'linux-debian-bin': (version, kernel_names),
            'systemd-boot-debian-bin': (records['systemd-boot-efi-amd64-signed']['Version'], ['systemd-boot-efi-amd64-signed']),
            'shim-debian-signed-bin': (records['shim-signed']['Version'], ['shim-signed', 'shim-helpers-amd64-signed']),
        }
        lock = {'suite': SUITE, 'architecture': 'amd64', 'kernel_abi': abi, 'packages': {}}
        for name, (native_version, names) in groups.items():
            entries = []
            for deb_name in names:
                data = records[deb_name]
                sha = data['SHA256']
                if not re.fullmatch('[0-9a-f]{64}', sha):
                    raise ValueError('Invalid SHA256')
                entries.append({'name': deb_name, 'version': data['Version'], 'filename': checked_path(data['Filename']), 'sha256': sha})
            lock['packages'][name] = {'debian_version': native_version, 'pkgver': pkgver(native_version), 'sources': entries}
            directory = ROOT / 'packages' / name
            directory.mkdir(parents=True, exist_ok=True)
            recipe_text = recipe(name, native_version, entries, abi if name == 'linux-debian-bin' else None)
            existing = directory / 'PKGBUILD'
            if existing.exists():
                recipe_text = preserve_release(recipe_text, existing.read_text())
            existing.write_text(recipe_text)
        (ROOT / 'sources.lock.json').write_text(json.dumps(lock, indent=4) + '\n')
        print(f'Resolved Debian {version}, ABI {abi}; authenticated archive metadata')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--keyring', type=Path, default=Path('/usr/share/keyrings/debian-archive-keyring.gpg'))
    args = parser.parse_args()
    update(args.keyring.resolve())
